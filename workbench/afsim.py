"""AFSIM 2.9 adapter: generated input, engine process, and AER extraction."""

import hashlib
import importlib.util
import math
import subprocess
import time
from pathlib import Path

from .model import write_json

EARTH_A = 6378137.0
EARTH_E2 = 6.69437999014e-3


def radii(latitude):
    lat = math.radians(latitude)
    denominator = 1 - EARTH_E2 * math.sin(lat) ** 2
    return EARTH_A / math.sqrt(denominator), EARTH_A * (1 - EARTH_E2) / denominator ** 1.5


def xy_to_geo(x, y, origin):
    n, m = radii(origin[0])
    return origin[0] + math.degrees(y / m), origin[1] + math.degrees(x / (n * math.cos(math.radians(origin[0]))))


def ecef_to_xy(position, origin):
    x, y, z = position["x"], position["y"], position["z"]
    horizontal = math.hypot(x, y)
    lat = math.atan2(z, horizontal * (1 - EARTH_E2))
    for _ in range(10):
        n = EARTH_A / math.sqrt(1 - EARTH_E2 * math.sin(lat) ** 2)
        lat = math.atan2(z + EARTH_E2 * n * math.sin(lat), horizontal)
    lon = math.atan2(y, x)
    n, m = radii(origin[0])
    return [math.radians(math.degrees(lon) - origin[1]) * n * math.cos(math.radians(origin[0])),
            math.radians(math.degrees(lat) - origin[0]) * m]


def angle(value, latitude):
    seconds = round(abs(value) * 3600, 6)
    degrees, seconds = divmod(seconds, 3600)
    minutes, seconds = divmod(seconds, 60)
    hemisphere = ("n" if value >= 0 else "s") if latitude else ("e" if value >= 0 else "w")
    return f"{int(degrees)}:{int(minutes):02d}:{seconds:09.6f}{hemisphere}"


def generate_scenario(config, routes, run_dir):
    effective = config["effective"]
    task, fleet, monitor = (effective[k] for k in ("coverage_task", "uav_fleet", "coverage_monitor"))
    origin = [task["origin_lat_deg"], task["origin_lon_deg"]]
    interval = monitor["sample_interval_s"]
    lines = ["# Generated by UAV Workbench 0.1; edit the engineering model instead.",
             f"end_time {config['engine']['horizon_s']} sec", ""]
    type_start = len(lines) + 1
    lines.extend(["platform_type WB_AIR WSF_PLATFORM", "   mover WSF_AIR_MOVER",
                  f"      update_interval {interval} sec", "      at_end_of_path stop",
                  f"      bank_angle_limit {fleet['bank_angle_limit_deg']} deg", "   end_mover", "end_platform_type", ""])
    source_map = [{"module": next(m["id"] for m in config["modules"] if m["type"] == "uav_fleet"),
                   "file": "scenario.txt", "start_line": type_start, "end_line": len(lines)-1}]
    for uav in fleet["uavs"]:
        start = len(lines) + 1
        uid = uav["id"]
        route = routes[uid]
        lines.append(f"platform {uid} {'WB_AIR' if len(route) > 1 else 'WSF_PLATFORM'}")
        if len(route) == 1:
            lat, lon = xy_to_geo(*route[0], origin)
            lines.extend([f"   position {angle(lat, True)} {angle(lon, False)}", f"   altitude {fleet['altitude_m']} m"])
        else:
            lines.append("   route")
            for point in route:
                lat, lon = xy_to_geo(*point, origin)
                lines.append(f"      position {angle(lat, True)} {angle(lon, False)} altitude {fleet['altitude_m']} m speed {uav['speed_mps']} m/s")
            lines.append("   end_route")
        lines.extend(["end_platform", ""])
        source_map.append({"module": next(m["id"] for m in config["modules"] if m["type"] == "uav_fleet"),
                           "instance": uid, "file": "scenario.txt", "start_line": start, "end_line": len(lines) - 1})
    start = len(lines) + 1
    lines.extend(["csv_event_output", "   file events.csv", "   disable all", "   enable PLATFORM_ADDED",
                  "   enable PLATFORM_DELETED", "   enable SIMULATION_STARTING", "   enable SIMULATION_COMPLETE",
                  "end_csv_event_output", "", "event_pipe", "   file replay.aer",
                  f"   maximum_mover_update_interval {interval} sec", "   disable_entity_state_thresholds",
                  f"   entity_state_maximum_interval {interval} sec", "end_event_pipe", ""])
    source_map.append({"module": next(m["id"] for m in config["modules"] if m["type"] == "coverage_monitor"),
                       "file": "scenario.txt", "start_line": start, "end_line": len(lines)})
    (run_dir / "scenario.txt").write_text("\n".join(lines), encoding="ascii")
    write_json(run_dir / "source_map.json", source_map)
    write_json(run_dir / "planned_routes.json", routes)
    return run_dir / "scenario.txt"


def run_mission(config, run_dir):
    executable = Path(config["engine"]["afsim_home"]) / "bin" / "mission.exe"
    started = time.perf_counter()
    command = [str(executable), "scenario.txt"]
    write_json(run_dir / "engine_invocation.json", {"command": command, "working_directory": str(run_dir),
               "executable_sha256": hashlib.sha256(executable.read_bytes()).hexdigest(),
               "wall_timeout_s": config["engine"]["wall_timeout_s"]})
    try:
        process = subprocess.run(command, cwd=run_dir, capture_output=True, timeout=config["engine"]["wall_timeout_s"],
                                 creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    except subprocess.TimeoutExpired as exc:
        (run_dir / "engine.log").write_bytes((exc.stdout or b"") + (exc.stderr or b""))
        raise RuntimeError("AFSIM 超过运行时间上限，详见 engine.log") from exc
    output = process.stdout + process.stderr
    (run_dir / "engine.log").write_bytes(output)
    if process.returncode != 0 or b"Simulation complete" not in output or not (run_dir / "replay.aer").is_file():
        raise RuntimeError(f"AFSIM 未正常完成，退出码 {process.returncode}，详见 engine.log 和 source_map.json")
    return {"wall_elapsed_s": time.perf_counter() - started, "returncode": process.returncode}


def read_trajectories(config, run_dir):
    module_path = Path(config["engine"]["afsim_home"]) / "bin" / "python" / "pymystic.py"
    spec = importlib.util.spec_from_file_location("local_pymystic", module_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    task = config["effective"]["coverage_task"]
    origin = [task["origin_lat_deg"], task["origin_lon_deg"]]
    names = {}
    trajectories = {u["id"]: [] for u in config["effective"]["uav_fleet"]["uavs"]}
    with module.Reader(str(run_dir / "replay.aer")) as reader:
        for message in reader:
            if message.get("msgtype") == "MsgPlatformInfo":
                names[message["platformIndex"]] = message["name"]
            elif message.get("msgtype") == "MsgEntityState":
                state = message["state"]
                name = names.get(state["platformIndex"])
                if name in trajectories:
                    xy = ecef_to_xy(state["locationWCS"], origin)
                    trajectories[name].append({"t": message["simTime"], "x": xy[0], "y": xy[1]})
    for name, points in trajectories.items():
        points.sort(key=lambda p: p["t"])
        horizon = config["engine"]["horizon_s"]
        clipped = [p for p in points if p["t"] <= horizon]
        if clipped and clipped[-1]["t"] < horizon:
            after = next((p for p in points if p["t"] > horizon), None)
            if after:
                before = clipped[-1]
                fraction = (horizon-before["t"])/(after["t"]-before["t"])
                clipped.append({"t": horizon, "x": before["x"]+fraction*(after["x"]-before["x"]),
                                "y": before["y"]+fraction*(after["y"]-before["y"])})
        points[:] = clipped
        if len(points) < 2:
            raise RuntimeError(f"{name} 缺少足够的轨迹状态，不能评价覆盖")
        if points[0]["t"] > 0.01 or points[-1]["t"] < config["engine"]["horizon_s"] - 0.01:
            raise RuntimeError(f"{name} 的轨迹未覆盖完整仿真时间")
        max_gap = max(b["t"] - a["t"] for a, b in zip(points, points[1:]))
        if max_gap > config["effective"]["coverage_monitor"]["sample_interval_s"] * 1.1 + 0.01:
            raise RuntimeError(f"{name} 的轨迹采样间隔过大，拒绝生成定量结论")
    write_json(run_dir / "trajectories.json", trajectories)
    return trajectories
